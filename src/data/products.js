export const products = [...electronics, ...stationery, ...graphics, ...others];

export const getProduct = (id) => products.find((p) => p.id === id) || null;

export const productsByCategory = (slug) =>
  products.filter((p) => p.category === slug);

export const searchProducts = (query) => {
  const q = query.trim().toLowerCase();
  if (!q) return products;
  return products.filter(
    (p) =>
      p.name.toLowerCase().includes(q) ||
      p.subcategory.toLowerCase().includes(q) ||
      p.categoryName.toLowerCase().includes(q) ||
      p.description.toLowerCase().includes(q)
  );
};

export const relatedProducts = (product, limit = 4) =>
  products
    .filter((p) => p.id !== product.id && p.category === product.category)
    .slice(0, limit);

export const allSubcategories = () => {
  const map = {};
  products.forEach((p) => {
    if (!map[p.category]) map[p.category] = [];
    if (!map[p.category].includes(p.subcategory)) map[p.category].push(p.subcategory);
  });
  return map;
};

export const formatPrice = (value) =>
  new Intl.NumberFormat('rw-RW', { style: 'currency', currency: 'RWF', maximumFractionDigits: 0 }).format(value);

export default products;
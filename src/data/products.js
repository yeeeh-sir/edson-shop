const u = (id, w = 800) =>
  `https://images.unsplash.com/${id}?auto=format&fit=crop&w=${w}&q=80`;

const defaultGraphicsOptions = {
  sizes: ['Small', 'Medium', 'Large'],
  materials: ['Standard', 'Premium'],
  printingOptions: ['Digital Print', 'Offset Print'],
  customization: true,
};

function prod({
  id,
  name,
  category,
  categoryName,
  subcategory,
  description,
  price,
  oldPrice,
  imageId,
  gallery,
  rating,
  reviews,
  stock,
  sku,
  featured,
  popular,
  isNew,
  isService,
  graphics,
}) {
  const discount = oldPrice && oldPrice > price ? Math.round(((oldPrice - price) / oldPrice) * 100) : 0;
  const unique = (arr) => Array.from(new Set(arr));
  return {
    id,
    name,
    category,
    categoryName,
    subcategory,
    description,
    price,
    oldPrice: oldPrice || null,
    discount,
    image: u(imageId),
    images: unique([...(gallery || []), imageId].map((x) => u(x))),
    rating: rating || 0,
    reviews: reviews || 0,
    stock,
    sku,
    featured: !!featured,
    popular: !!popular,
    isNew: !!isNew,
    isService: !!isService,
    graphics: isService
      ? { ...defaultGraphicsOptions, ...graphics }
      : undefined,
  };
}

